"""Generates GalleryOracleExpected.cs: the answers of the Python oracle (tools/tsuki/misc_gallery_extras_flowchart.py, docs/formats/gallery.md) to the
gallery and flowchart unlock questions on seven deterministic progress states. The C# test (GalleryRealDataTests) builds the same states with
GalleryOracleStates and compares its own answers with these arrays.

Run:  PYTHONPATH=D:/TsukihimePort/tools .venv/Scripts/python.exe tests/Tsuki.Tests.Data/Ui/gen_gallery_oracle.py
(needs TSUKI_GAME_DIR or the default game folder: it reads the eboot.)
"""
import sys
from pathlib import Path

from tsuki import misc_gallery_extras_flowchart as gx


def h(i: int, salt: int) -> int:
    """The state bit hash shared with GalleryOracleStates.Hash: 12 bits."""
    return ((i * 2654435761 + salt * 40503) & 0xFFFFFFFF) >> 20


def build(name: str) -> gx.UnlockState:
    s = gx.UnlockState()

    def seen_all():
        for n in range(576):
            s.set_scene_seen(n)

    if name == "empty":
        return s
    if name in ("sparse", "sparse_all_cg"):
        for n in range(576):
            if h(n, 1) < 2048:
                s.set_scene_seen(n)
            if h(n, 2) < 1500:
                s.set_scene_done(n)
        for cid in range(564, 1268):
            if h(cid, 3) < 1800:
                s.set_choice_seen(cid)
        for i in range(3200):
            if h(i, 4) < 2000:
                s.set_picture_bit(i)
        for t in range(0x208):
            if h(t, 5) < 1500:
                s.set_bgm_heard(t)
        for b in range(16):
            if h(b, 6) < 2048:
                s.g[gx.G_MOVIE] |= 1 << b
        if name == "sparse_all_cg":
            seen_all()
            s.set_scene_done(557)
        return s
    if name == "edges_only":
        for cid in range(564, 1268):
            s.set_choice_seen(cid)
        return s
    if name == "only_qa25":
        s.set_scene_done(557)
        return s
    if name == "seen_prefix":
        seen_all()
        for n in range(1, 101):
            s.set_scene_done(n)
        return s
    if name == "everything":
        for n in range(576):
            s.set_scene_seen(n)
            s.set_scene_done(n)
        for cid in range(564, 1268):
            s.set_choice_seen(cid)
        for i in range(3200):
            s.set_picture_bit(i)
        for t in range(0x208):
            s.set_bgm_heard(t)
        s.g[gx.G_MOVIE] = 0xFFFF
        return s
    raise ValueError(name)


STATES = ["empty", "sparse", "sparse_all_cg", "only_qa25", "seen_prefix", "edges_only", "everything"]


def main() -> None:
    d = gx.load()
    raw = gx.FlowRaw.from_eboot(__import__("eboot").eboot_path())
    entries = d.cg_entries
    index_of = {id(e): i for i, e in enumerate(entries)}
    out = []
    out.append("// <auto-generated> by gen_gallery_oracle.py: the Python oracle's answers on the seven GalleryOracleStates. Do not edit. </auto-generated>")
    out.append("namespace Tsuki.Tests.Data.Ui;")
    out.append("")
    out.append("internal static class GalleryOracleExpected")
    out.append("{")
    out.append("    /// <summary>The CG entries (flat index in group order) that are unlocked.</summary>")
    out.append("    public static IReadOnlyList<int> Cg(string state) => state switch")
    out.append("    {")
    results = {}
    for name in STATES:
        s = build(name)
        u = gx.Unlocks(d, s)
        cg = [i for i, e in enumerate(entries) if u.cg_unlocked(e)]
        tiles = [g.index for g, _first, _n in u.cg_main_tiles()]
        music = [i for i, t in enumerate(d.music) if u.music_unlocked(t)]
        extras = [i for i in range(len(d.extras)) if u.extra_unlocked(i)]
        movies = [i for i in range(3) if u.movie_unlocked(i)]
        kept = gx.flow_filter(raw, s)
        results[name] = (cg, tiles, music, extras, movies, kept)
    def arr(v):
        return "[" + ", ".join(str(x) for x in v) + "]"
    for q, label in enumerate(["Cg", "Tiles", "Music", "Extras", "Movies", "Kept"]):
        if q == 0:
            for name in STATES:
                out.append(f'        "{name}" => {arr(results[name][0])},')
            out.append('        _ => throw new ArgumentOutOfRangeException(nameof(state)),')
            out.append("    };")
            continue
        out.append("")
        out.append(f"    public static IReadOnlyList<int> {label}(string state) => state switch")
        out.append("    {")
        for name in STATES:
            out.append(f'        "{name}" => {arr(results[name][q])},')
        out.append('        _ => throw new ArgumentOutOfRangeException(nameof(state)),')
        out.append("    };")
    out.append("}")
    path = Path(__file__).with_name("GalleryOracleExpected.cs")
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    for name in STATES:
        r = results[name]
        print(name, "cg", len(r[0]), "tiles", len(r[1]), "music", len(r[2]), "extras", len(r[3]), "movies", r[4], "kept", len(r[5]))


if __name__ == "__main__":
    main()
