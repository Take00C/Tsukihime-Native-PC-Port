@needs_emu
def test_first_byte_sweep(emu: mv.VarEmu) -> None:
    """Every byte as the first byte of every operand position (and byte 1 of '_' operands,
    GOTS selectors and choice targets): engine == model in every run, and the dispatch is
    exactly the one vm_variables.md 3.2 tabulates."""
    pre_bytes = list(b"CFGZ_`eglnx0129 -Dc") + [0, 0x80, 0xFF]   # full set: CLI `sweep`
    groups, bad, runs = mv.first_byte_sweep(emu, pre_bytes)
    assert runs == 21 * 253 + 15 * len(pre_bytes) and not bad, bad[:3]   # 21 readers, 15 also prefetch

    def var_bytes(reader: str) -> dict:
        return {cls: bytes(bs).decode("latin-1") for cls, bs in groups[reader].items() if len(bs) < 20}
    assert var_bytes("WKST target") == {"writes F[17]": "C", "writes G[12]": "G", "writes F[12]": "F_"}
    assert var_bytes("prefetch WKST target") == {"writes G[12]": "G", "writes F[12]": "F_",
                                                 "no effect": "CZ`eglnx0129 -Dc\x00\x80\xff"}
    assert var_bytes("WKOR target") == {"reads G[12]; writes G[12]": "G", "reads F[12]; writes F[12]": "F_"}
    assert var_bytes("WKBO target") == {"reads F[12]; writes F[12]": "F", "reads G[12]; writes G[12]": "G"}
    assert var_bytes("WKBO value") == {}
    for r in ("WKST value", "WKAD value", "WKOR value", "WKOF value", "prefetch WKST value"):
        got = var_bytes(r)
        got.pop("writes F[5]", None)                 # the literal class (small in the prefetch subset)
        assert got == {"reads G[12]; writes F[5]": "G", "reads F[12]; writes F[5]": "F_",
                       "reads F[0]; writes F[5]": "`"}, r
    assert var_bytes("IF__ rhs") == {"reads G[12]; goto argument 3": "G", "reads F[12]; goto argument 3": "F_"}
    assert var_bytes("IF__ operator, second byte 'e', F5 = 12") == {"no effect": "egl"}
    assert var_bytes("IF__ operator, second byte 'x', F5 = 13") == {"no effect": "gn"}
    assert var_bytes("GOTS selector byte 0, F0 = 1") == {"reads F[0]; goto argument 2": "_"}
    assert list(groups["GOTS selector byte 1, F0 = 1"]) == ["reads F[0]; goto argument 2"]
    assert var_bytes("SELD target byte 0") == {"choice kind 'F'": "_"}
    assert var_bytes("SELD target byte 1") == {"choice kind 'F'": "D"}
    g2, bad2, runs2 = mv.choice_setter_sweep(emu)
    assert runs2 == 1008 and not bad2, bad2[:3]
    for name in ("SELA", "SELS"):
        assert {c: bytes(b).decode("latin-1") for c, b in g2[f"{name} target byte 0"].items() if len(b) < 20}             == {"kind F index 12": "_"}
        assert {c: bytes(b).decode("latin-1") for c, b in g2[f"{name} target byte 1"].items() if len(b) < 20}             == {"kind F index 12": "D"}


def _writes(case: dict) -> list:
    return [tuple(w) for w in case["writes"]]


@needs_emu
def test_choice_commands_under_flags(emu: mv.VarEmu) -> None:
    """Review fix: SELA / SELS / SELD / SELR through ScriptStep's own handlers under scan
    mode, F1118 and the History_Snapshot gate words; engine == model in every case."""
    cases = mv.choice_flag_cases(emu)
    assert len(cases) == 32 and not [c for c in cases if c[2]], [c for c in cases if c[2]][:3]
    by = {(t, c.get("scan"), c.get("F1118")): c for t, c, _d in cases if not t.startswith("_SELR")}
    sela_open = by[("_SELA(_D000,);", False, 0)]
    assert sela_open["ui"] and sela_open["mode"] == 3 and sela_open["kind"] == 0x46
    assert _writes(sela_open) == [("F[1118]", 0)]
    for scan, f1118 in ((False, 1), (True, 0), (True, 1)):
        c = by[("_SELA(_D000,);", scan, f1118)]
        assert not c["ui"] and c["yield"] and c["kind"] == 0x11 and c["mode"] == 0
        assert _writes(c) == [("F[1118]", 0)]                            # F1118 always cleared
    for t in ("_SELS(_D000,);", "_SELD(_D005,7);"):
        assert by[(t, False, 1)]["ui"] and not by[(t, True, 0)]["ui"] and by[(t, True, 0)]["kind"] == 0x11
    selr = {(c["scan"], c["F929"], c["F1102"], c["block"]): c for t, c, _d in cases if t.startswith("_SELR")}
    assert [k for k, c in selr.items() if c["snapshot"]] == [(False, 0, 0, 0)]
    assert selr[(False, 0, 1, 0)]["reads"] == ["F[929]", "F[1102]", "F[823]", "F[850]"]
    assert selr[(False, 1, 0, 0)]["reads"] == ["F[929]", "F[823]", "F[850]"]
    assert selr[(True, 0, 0, 0)]["reads"] == ["F[823]", "F[850]"]           # scan: no gate read
    nreads, writes, err = mv.snapshot_body_writes(emu)
    assert err is None and nreads > 100 and writes == [("F[850]", mv.pattern(F(850)) + 1)]


