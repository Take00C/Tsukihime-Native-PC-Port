@needs_eboot
def test_history_lists() -> None:
    assert EBOOT is not None
    u16, bl, s8 = mv.read_history_lists(EBOOT)
    assert (u16, bl, s8) == (list(vv.HISTORY_U16), list(vv.HISTORY_BOOL), list(vv.HISTORY_S8))
    assert (len(u16), len(bl), len(s8)) == (39, 43, 276)
    kept = set(u16) | set(bl) | set(s8)
    assert len(kept) == 356 and max(kept) < 1200
    assert set(u16) & set(bl) == {991} and set(u16) & set(s8) == {967} and not set(bl) & set(s8)
    # restore order u16 -> s8 -> bool: the later list decides the storage
    assert vv.history_storage(991) == "bool" and vv.history_storage(967) == "s8"
    assert vv.history_roundtrip(848, 63) == 63 and vv.history_roundtrip(848, 200) == 0xFFC8
    assert vv.history_storage(1102) is None and vv.history_roundtrip(1102, 5) == 0   # transient
    assert vv.history_roundtrip(929, 5) == 1 and vv.history_roundtrip(1104, 7) == 1  # bool


