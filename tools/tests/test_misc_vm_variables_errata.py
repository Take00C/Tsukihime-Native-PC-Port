@needs_emu
def test_erratum_a_c_operands(emu: mv.VarEmu) -> None:
    """C<n> as a WKST/WKAD target is F[F823 + n]; with F823 = 0 (its value in the eboot
    image) that is the F[n] alias the re-check saw (0x164B86E = F[847]).  In a value slot
    C, Z and X are literals."""
    r = emu.run(b"_WKST(C847,eq,0);_DMMY();", fill=mv.pattern, init={F(823): 0})
    assert [(k, a) for k, a, _v in r.log] == [("r", F(823)), ("w", 0x164B86E)]
    r = emu.run(b"_WKAD(C847,5);_DMMY();", fill=mv.pattern, init={F(823): 0, F(847): 2})
    assert r.log[-1] == ("w", 0x164B86E, 7)
    r = emu.run(b"_WKST(C847,eq,63);_DMMY();", fill=mv.pattern, init={F(823): 5})
    assert r.log[-1] == ("w", F(852), 63)
    r = emu.run(b"_WKST(C859,eq,0);_DMMY();", fill=mv.pattern, init={F(823): 3})
    assert r.log[-1] == ("w", F(862), 0)
    for lit in ("C3", "Z3", "X3", "c3", "D3"):
        r = emu.run(f"_WKST(F12,eq,{lit});_DMMY();".encode(), fill=mv.pattern)
        assert r.log == [("w", F(12), 3)], lit
    for var, va in (("F3", F(3)), ("G3", vv.VAR_G + 6), ("_D003", F(3))):
        r = emu.run(f"_WKST(F12,eq,{var});_DMMY();".encode(), fill=mv.pattern)
        assert r.log == [("r", va, mv.pattern(va)), ("w", F(12), mv.pattern(va))], var
    # Script_Prefetch has no C case (and no Z case): nothing is written
    r = emu.run(b"_WKST(C847,eq,0);_DMMY();", fill=mv.pattern, init={F(823): 5}, prefetch=True)
    assert not [x for x in r.log if x[0] == "w"]


