def test_erratum_b_regenerated_table() -> None:
    """samples/engine/vm_commands.json (regenerated by eboot.scriptvm with setcc support):
    Script_Prefetch has 43 entries, 41 names + J*** + ZY**, and no V*** wildcard."""
    p = ROOT / "samples" / "engine" / "vm_commands.json"
    if not p.exists():
        pytest.skip("samples/engine/vm_commands.json not generated")
    d = json.loads(p.read_text(encoding="utf-8"))
    pre = next(t for t in d if t["interpreter"] == 0x9B760)
    names = [c["name"] for c in pre["commands"]]
    assert len(names) == 43 and [n for n in names if "*" in n] == ["J***", "ZY**"]
    assert [n for n in names if n[0] == "V"] == ["VPL2", "VPLY"]
    main = next(t for t in d if t["interpreter"] == 0x95E60)
    assert len(main["commands"]) == 112
    assert [c["name"] for c in main["commands"] if c["name"][0] == "V"] == ["VCLR", "VCWT", "VPL2", "VPLY"]


