@needs_emu
def test_eif_condition_evaluator_reads_z(emu: mv.VarEmu) -> None:
    """Script_EvalCondition (VA 0x79D30) belongs to _EIF_ (0 uses in the scripts): it reads
    bracketed F[n] / Z[n] / G[n]; _IF__ never calls it (Z is a literal there)."""
    out = {}
    for t in mv.EVAL_CASES:
        res, log, _end, err = mv.run_eval_condition(emu, t)
