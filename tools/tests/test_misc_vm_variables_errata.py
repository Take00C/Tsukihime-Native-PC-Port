@needs_game
def test_corpus_census_and_classification() -> None:
    res = mv.corpus_census()
    assert res["scripts"] == 549
    assert res["segments"] == 1_083_168                     # erratum (d)
    # the old count 1,083,717 = split(';') pieces: one empty piece after each script's last ';'
    assert res["segments_split_count"] == 1_083_717 and res["scripts_ending_with_semicolon"] == 549
    k = res["kinds"]
    assert isinstance(k, dict)
    assert k["WKST.0"] == {"F": 402_379, "C": 85_471, "G": 7}
    assert k["WKST.2"] == {"lit": 487_836, "F": 20, "G": 1}
    assert k["WKAD.0"] == {"F": 42_604, "C": 3_075} and k["WKAD.1"] == {"lit": 45_679}
    assert k["IF__.0"] == {"F": 641, "G": 553} and k["IF__.2"] == {"lit": 1194}
    assert k["WKOR.0"] == {"G": 21}
    for c, n in (("GOTS", 170), ("SELD", 170), ("SELA", 26), ("SELS", 1)):
        assert k[f"{c}.0"] == {"F": n}
        assert res["forms"][f"{c}.0"] == {"_Dddd": n}        # type: ignore[index]
    assert res["c_uses_by_command"] == {"WKAD.C847": 3_075, "WKST.C847": 42_881, "WKST.C859": 42_590}
    assert res["max_f823_linear"] == 10
    cu = res["c_uses_by_f823"]
    assert isinstance(cu, dict)
    assert sorted(int(x) for x in cu["847"]) == list(range(0, 11))
    assert sorted(int(x) for x in cu["859"]) == list(range(1, 11))
    assert res["statements"]["SELR"] == 824                 # type: ignore[index]
    # every F index a script touches is kept by a history record / save slot, and every
    # literal value the scripts store survives the storage class; every G is system data
    f = res["f_indices"]
    g = res["g_indices"]
    assert isinstance(f, dict) and isinstance(g, dict)
    assert len(f) == 78 and res["f_storage_counts"] == {"u16": 13, "s8": 38, "bool": 27}
    assert res["literal_values_not_surviving_a_save"] == []
    assert f["0"]["uses"] == {"SELD.0": 170, "GOTS.0": 170, "SELA.0": 26, "SELS.0": 1}
    assert len(g) == 18 and all(v["storage"] == "system-data" for v in g.values())
    assert max(int(x) for x in g) == 70
